    d.text((820, 430), "обвалование ~3 м", fill=(255, 255, 255), font=F(SANSB, 20))

    # rules
    rules = [
        "1. Выбирать площадку с естественной маскировкой (лес, складки местности, овраги).",
        "2. Рассредоточивать бунты / транспорт; избегать геометрически правильных рядов с воздуха.",
        "3. Использовать штатные маскировочные сети и местные материалы под фон местности.",
        "4. Укрытия: котлован + накат + грунт ≥ 50 см; аппарели с противопыльными занавесями.",
        "5. Светомаскировка: ночные работы — приглушённый свет, экраны, запрет открытого освещения.",
        "6. Следы техники маскировать; подъезды — по существующим дорогам/колеям.",
        "7. Имущество текущего снабжения и НЗ / длительного хранения — раздельно.",
        "8. Пожарная безопасность и охрана — обязательны и в полевых условиях.",
    ]
    y = 560
    for r in rules:
        rounded(d, (60, y, 1340, y + 34), (255, 255, 255), outline=(160, 180, 150), r=6, w=1)
