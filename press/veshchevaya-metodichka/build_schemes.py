#!/usr/bin/env python3
"""Схемы-иллюстрации к методичке вещевой службы ВС РФ."""

from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent
IMG = ROOT / "images"
IMG.mkdir(parents=True, exist_ok=True)

SANS = "/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf"
SANSB = "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf"


def F(path, size):
    return ImageFont.truetype(path, size)


def rounded(draw, box, fill, outline=(200, 200, 200), r=12, w=2):
    draw.rounded_rectangle(box, radius=r, fill=fill, outline=outline, width=w)


def title(draw, text, y=24, size=30):
    draw.text((40, y), text, fill=(25, 25, 25), font=F(SANSB, size))


def build_warehouse_layout():
    W, H = 1400, 1000
    img = Image.new("RGB", (W, H), (248, 246, 242))
    d = ImageDraw.Draw(img)
    title(d, "Схема вещевого склада воинской части (учебная)", 20, 28)
    d.text((40, 58), "Раздельное хранение по кладовым · стеллажные нормативы · охрана", fill=(90, 90, 90), font=F(SANS, 18))

    # outer building
    d.rectangle((60, 100, 980, 920), outline=(40, 40, 40), width=3, fill=(255, 255, 255))
