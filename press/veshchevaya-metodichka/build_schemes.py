        (80, 120, 420, 360, "1. Расходная\nновое обмундирование\nи обувь (+ примерочная)", (220, 235, 255)),
        (440, 120, 780, 360, "2. Бывшее в употреблении\nи фонд сборов", (255, 240, 220)),
        (800, 120, 960, 360, "3. Грязное\nбельё", (255, 225, 225)),
        (80, 380, 300, 620, "4. Моющие\nи ремонт", (230, 255, 230)),
        (320, 380, 540, 620, "5. Спорт\nлыжи / инвентарь", (235, 230, 255)),
        (560, 380, 780, 620, "6. Ветошь\nвыбраковка", (245, 245, 220)),
