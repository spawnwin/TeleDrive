def font_run(run, size=12, bold=False):
    run.font.name = "Times New Roman"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    run.font.size = Pt(size)
    run.bold = bold
    run.font.color.rgb = RGBColor(0, 0, 0)


def add_h(doc, text, level=1):
    p = doc.add_heading(text, level=level)
    for run in p.runs:
        font_run(run, size=16 if level == 1 else 14, bold=True)
    return p


def add_p(doc, text, *, first=True):
    p = doc.add_paragraph()
    p.paragraph_format.first_line_indent = Cm(1.25) if first else Cm(0)
    p.paragraph_format.space_after = Pt(6)
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    run = p.add_run(text)
    font_run(run, 12)
    return p


def add_bullets(doc, items):
    for it in items:
        p = doc.add_paragraph(style="List Bullet")
        p.clear()
        run = p.add_run(it)
        font_run(run, 12)


def add_img(doc, name, caption):
    path = IMG / name
    if path.exists():
        doc.add_picture(str(path), width=Inches(6.2))
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = p.add_run(caption)
        font_run(run, 10)
        run.italic = True


